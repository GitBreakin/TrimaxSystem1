-- =====================================================================================================
-- The 11 Desktop tables exactly as production has them on 2026-10-26 (after 20261025_06).
--
-- WHY: these tables were created long ago by the Desktop's own SQL, which is in no repository file, so a
-- database rebuilt from this repository was only an approximation (sql/tests/01_... is a test
-- reconstruction). This file was written from production's catalog (column types, defaults, identity,
-- constraint and index definitions as PostgreSQL prints them), read-only.
--
-- USE: rebuilding a database from scratch (a new Supabase project, a staging copy, disaster recovery):
--   1. this file
--   2. 20261023_01, 20261023_02, 20261025_01 ... 20261025_06 in order (they are re-runnable; where a
--      column is already here, their "add column if not exists" does nothing).
-- Left to 20261023_01 (it creates them, with the same definitions production has): the shared-booking
-- columns and checks on bookings, and the index clients_contact_key_idx (needs trimax_private.contact_key).
-- Checked 2026-10-26: a database built this way has the same columns, constraints, indexes, RLS and API
-- grants as production on all 19 tables (per-table fingerprints compared).
--
-- PRODUCTION: nothing to do. Every statement is a no-op there (create ... if not exists). Do not run it
-- on production anyway without approval. Contains no data and no passwords.
-- =====================================================================================================

begin;

create table if not exists public.roles (
    role_id    integer generated by default as identity not null,
    role_name  character varying(20) not null,
    constraint roles_pkey primary key (role_id),
    constraint roles_role_name_key unique (role_name)
);

create table if not exists public.users (
    username         character varying(50)  not null,
    password         character varying(255) not null,
    name             character varying(100) not null,
    contact_num      character varying(20),
    email            character varying(100) not null,
    role_id          integer not null,
    account_status   character varying(10) not null default 'Active'::character varying,
    failed_attempts  integer not null default 0,
    locked_until     timestamp with time zone,
    constraint users_pkey primary key (username),
    constraint users_email_key unique (email),
    constraint users_role_id_fkey foreign key (role_id) references public.roles(role_id) on delete restrict,
    constraint users_account_status_check check (account_status in ('Active', 'Inactive', 'Pending'))
);
create index if not exists idx_users_role on public.users using btree (role_id);

create table if not exists public.clients (
    client_id    integer generated by default as identity not null,
    client_name  character varying(100) not null,
    address      character varying(150),
    contact_num  character varying(20),
    longitude    numeric(10,7),
    latitude     numeric(10,7),
    constraint clients_pkey primary key (client_id),
    constraint clients_latitude_check check (((latitude >= ('-90'::integer)::numeric) AND (latitude <= (90)::numeric))),
    constraint clients_longitude_check check (((longitude >= ('-180'::integer)::numeric) AND (longitude <= (180)::numeric)))
);
create unique index if not exists clients_unique_name_address on public.clients using btree (lower(regexp_replace(btrim((client_name)::text), '\s+'::text, ' '::text, 'g'::text)), lower(regexp_replace(btrim((COALESCE(address, ''::character varying))::text), '\s+'::text, ' '::text, 'g'::text)));

create table if not exists public.vehicles (
    vehicle_id        character varying(20) not null,
    username          character varying(50),
    vehicle_type      character varying(30),
    status            character varying(20) not null default 'Available'::character varying,
    latitude          numeric(10,7),
    longitude         numeric(10,7),
    last_location_at  timestamp with time zone,
    constraint vehicles_pkey primary key (vehicle_id),
    constraint vehicles_username_fkey foreign key (username) references public.users(username) on update cascade on delete set null,
    constraint vehicles_latitude_check check (((latitude >= ('-90'::integer)::numeric) AND (latitude <= (90)::numeric))),
    constraint vehicles_longitude_check check (((longitude >= ('-180'::integer)::numeric) AND (longitude <= (180)::numeric))),
    constraint vehicles_status_check check (status in ('Available', 'On Delivery', 'Maintenance', 'Unavailable', 'On Vacation', 'Suspended'))
);
create index if not exists idx_vehicles_username on public.vehicles using btree (username);

create table if not exists public.agents (
    agent_id          integer generated by default as identity not null,
    username          character varying(50) not null,
    client_id         integer not null,
    longitude         numeric,
    latitude          numeric,
    last_location_at  timestamp with time zone,
    constraint agents_pkey primary key (agent_id),
    constraint agents_username_client_id_key unique (username, client_id),
    constraint agents_client_id_fkey foreign key (client_id) references public.clients(client_id) on delete cascade,
    constraint agents_username_fkey foreign key (username) references public.users(username) on update cascade on delete cascade
);
create index if not exists idx_agents_client on public.agents using btree (client_id);

create table if not exists public.products (
    product_id        integer generated by default as identity not null,
    product_name      character varying(100) not null,
    supplier          character varying(100),
    price             numeric(10,2) not null,
    stock             integer not null default 0,
    image_path        text,
    image_updated_at  timestamp with time zone,
    constraint products_pkey primary key (product_id),
    constraint products_product_name_supplier_key unique (product_name, supplier),
    constraint products_image_path_chk check (((image_path IS NULL) OR (image_path ~ '^products/[0-9]{1,9}/[A-Za-z0-9_-]{1,80}\.jpg$'::text))),
    constraint products_price_check check ((price >= (0)::numeric)),
    constraint products_stock_check check ((stock >= 0))
);

create table if not exists public.bookings (
    booking_id            integer generated by default as identity not null,
    client_id             integer not null,
    transc_date           timestamp with time zone not null default now(),
    total_amount          numeric(12,2) not null default 0,
    driver_username       character varying(50),
    vehicle_id            character varying(20),
    status                character varying(20) not null default 'Pending'::character varying,
    constraint bookings_pkey primary key (booking_id),
    constraint bookings_client_id_fkey foreign key (client_id) references public.clients(client_id) on delete restrict,
    constraint bookings_driver_username_fkey foreign key (driver_username) references public.users(username) on update cascade on delete set null,
    constraint bookings_vehicle_id_fkey foreign key (vehicle_id) references public.vehicles(vehicle_id) on update cascade on delete set null,
    constraint bookings_status_check check (((status)::text = ANY (ARRAY['Pending'::text, 'Confirmed'::text, 'In Progress'::text, 'Completed'::text, 'Cancelled'::text]))),
    constraint bookings_total_amount_check check ((total_amount >= (0)::numeric))
);
-- The shared-booking columns (created_via ... last_changed_at), their checks, bookings_created_by_fk and the
-- indexes bookings_client_request_id_key / bookings_created_by_idx / bookings_driver_status_idx come from
-- 20261023_01_mobile_booking_integration.sql, run next.
create index if not exists idx_bookings_client on public.bookings using btree (client_id);
create index if not exists idx_bookings_date on public.bookings using btree (transc_date DESC);
create index if not exists idx_bookings_driver on public.bookings using btree (driver_username);

create table if not exists public.booking_items (
    item_id     integer generated by default as identity not null,
    booking_id  integer not null,
    product_id  integer not null,
    quantity    integer not null,
    unit_price  numeric(10,2) not null,
    subtotal    numeric(12,2) not null,
    constraint booking_items_pkey primary key (item_id),
    constraint booking_items_booking_id_product_id_key unique (booking_id, product_id),
    constraint booking_items_booking_id_fkey foreign key (booking_id) references public.bookings(booking_id) on delete cascade,
    constraint booking_items_product_id_fkey foreign key (product_id) references public.products(product_id) on delete restrict,
    constraint booking_items_check check ((subtotal = ((quantity)::numeric * unit_price))),
    constraint booking_items_quantity_check check ((quantity > 0)),
    constraint booking_items_unit_price_check check ((unit_price >= (0)::numeric))
);
create index if not exists idx_items_booking on public.booking_items using btree (booking_id);
create index if not exists idx_items_product on public.booking_items using btree (product_id);

create table if not exists public.login_sessions (
    token_hash  character(64) not null,
    username    character varying(50) not null,
    created_at  timestamp with time zone not null default now(),
    expires_at  timestamp with time zone not null,
    constraint login_sessions_pkey primary key (token_hash),
    constraint login_sessions_username_fkey foreign key (username) references public.users(username) on update cascade on delete cascade
);
create index if not exists idx_login_sessions_user on public.login_sessions using btree (username);

create table if not exists public.password_resets (
    reset_id    integer generated by default as identity not null,
    username    character varying(50) not null,
    code_hash   character(64) not null,
    expires_at  timestamp with time zone not null,
    attempts    integer not null default 0,
    used        boolean not null default false,
    created_at  timestamp with time zone not null default now(),
    constraint password_resets_pkey primary key (reset_id),
    constraint password_resets_username_fkey foreign key (username) references public.users(username) on update cascade on delete cascade
);
create index if not exists idx_password_resets_user on public.password_resets using btree (username);

create table if not exists public.audit_log (
    audit_id        bigserial not null,
    occurred_at     timestamp with time zone not null default now(),
    actor_username  character varying not null,
    action          text not null,
    target_type     text not null,
    target_id       text not null,
    result          text not null default 'success'::text,
    details         text,
    constraint audit_log_pkey primary key (audit_id),
    constraint audit_log_actor_username_fkey foreign key (actor_username) references public.users(username)
);
create index if not exists audit_log_target_idx on public.audit_log using btree (target_type, target_id, occurred_at DESC);
create index if not exists audit_log_time_idx on public.audit_log using btree (occurred_at DESC);

-- As on production: row level security on, no policies, no direct access for the API roles (phones use
-- the trimax_* functions; the Desktop connects as the owner).
do $$
declare
    t text;
begin
    foreach t in array array['roles', 'users', 'clients', 'vehicles', 'agents', 'products', 'bookings',
                             'booking_items', 'login_sessions', 'password_resets', 'audit_log'] loop
        execute format('alter table public.%I enable row level security', t);
        if exists (select 1 from pg_roles where rolname = 'anon') then
            execute format('revoke all on table public.%I from anon', t);
        end if;
        if exists (select 1 from pg_roles where rolname = 'authenticated') then
            execute format('revoke all on table public.%I from authenticated', t);
        end if;
    end loop;
end $$;

commit;
